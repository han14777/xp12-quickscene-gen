"""Step 4, build_dsf: write DSF text -> compile with DSFTool -> decompile and check counts.
An area spanning several 1-degree tiles gets one DSF per tile.

The DSF text follows melbourne-cbd-xp12 pipeline/04_build_dsf.py, all verified in X-Plane 12:
- Property order as WED writes it (sim/west|east|north|south first); sim/overlay 1; sim/require_facade 1/0
- Exclusions use only dsf.exclusion_types (default obj, fac), tiled from west/south/east/north rectangles:
  polygon exclusion zones have no effect in XP12, rectangles do
- Facades: BEGIN_POLYGON <index> <height> 2, one lon lat per point, outer ring counter-clockwise without
  repeating the first point, holes dropped. Heights must be integers: DSFTool silently drops the whole
  polygon on a fractional height, so the DSF is decompiled after compiling and any count mismatch fails the build
- Facades cannot have holes: blocks with courtyards are cut along vertical lines through each hole
  (split_holes), otherwise the courtyard would be filled in
- Blocks go to the tile containing their centroid; blocks with vertices outside that tile are skipped and counted
- Buildings edited to delete or to a custom model (overrides.py) get no facade or distant block; a model is
  placed with OBJECT at the building origin plus its offset and heading. Models from jobs/<name>/models/ are copied
  to objects/models/ in the pack (the whole folder, so textures come along); library paths are used as given
- Distant blocks (impostors.py) beyond the facades' LOD up to dsf.render_distance_km: OBJECT_DEF <path relative to
  the pack root>, OBJECT <index> <lon> <lat> <heading> (README.dsf2text), with sim/require_object 1/0 like the
  facades so they load at any object density

- Placed items (placements.py: objects, facades, forests, draped polygons, lines, object strings from any library or
  the job's models folder) and OSM trees (vegetation.py) are added as OBJECT / BEGIN_POLYGON entries; polygons get
  one BEGIN_WINDING per ring. The virtual paths used are looked up in the installed libraries
  (library.py) and listed in build_report.json and README.txt as required libraries; paths no installed library
  exports are reported as missing (X-Plane would show nothing for them)

Output: processed/<tile>.dsf.txt, build/<pack>/Earth nav data/<10-degree folder>/<tile>.dsf,
build/<pack>/objects/impostors/, README.txt, build/<pack>/cityscene/ (the job, for re-importing; transfer.py),
build_report.json
"""

import json
import math
import shutil
import subprocess
from collections import Counter, defaultdict
from pathlib import Path

import shapely
from shapely.geometry import Polygon, box, mapping, shape
from shapely.geometry.polygon import orient

from cityscene.tools_setup import ensure_dsftool
from cityscene import impostors, overrides, placements, transfer, vegetation
from cityscene.dsf_rects import exclusion_rects
from cityscene.geo import Projector, metric_crs_for, tile_dir, tile_name, tiles_for, zones_union
from cityscene.log import get_logger

log = get_logger("build_dsf")

# Consecutive points closer than this (metres) are treated as duplicates, avoiding zero-length edges
MIN_EDGE_M = 0.05
AGENT = "xp12-cityscene-gen"
ATTRIBUTION = """{name} for X-Plane 12
Generated by xp12-cityscene-gen.

Data sources:
- Building footprints and heights: (c) OpenStreetMap contributors, ODbL 1.0
  (https://www.openstreetmap.org/copyright)
- Facades: X-Plane 12 default library (Laminar Research), no extra download required

The cityscene folder holds the job (area, settings, edits, cleaned OSM buildings) so this pack can be
imported back into xp12-cityscene-gen, edited and regenerated. X-Plane ignores it.
"""


def prepare_ring(polygon_m: Polygon) -> tuple[list | None, str | None, bool]:
    """Returns (counter-clockwise outer ring without the closing point, in projected coordinates; failure reason; whether holes were dropped)."""
    had_holes = len(polygon_m.interiors) > 0
    exterior = orient(Polygon(polygon_m.exterior), sign=1.0)
    coords = list(exterior.exterior.coords)[:-1]
    cleaned = []
    for x, y in coords:
        if not cleaned or (x - cleaned[-1][0]) ** 2 + (y - cleaned[-1][1]) ** 2 >= MIN_EDGE_M**2:
            cleaned.append((x, y))
    while len(cleaned) > 1 and (cleaned[0][0] - cleaned[-1][0]) ** 2 + (cleaned[0][1] - cleaned[-1][1]) ** 2 < MIN_EDGE_M**2:
        cleaned.pop()
    if len(cleaned) < 3:
        return None, "too_few_points", had_holes
    ring = Polygon(cleaned)
    if not ring.is_valid or ring.area <= 0:
        return None, "invalid_after_cleanup", had_holes
    return cleaned, None, had_holes


def split_holes(geom) -> list:
    """Cut a polygon with holes along vertical lines through the holes until none remain; returns the pieces (from melbourne-cbd-xp12)."""
    todo = [g for g in getattr(geom, "geoms", [geom]) if g.geom_type == "Polygon" and not g.is_empty]
    out = []
    while todo:
        poly = todo.pop()
        if not poly.interiors:
            out.append(poly)
            continue
        x = shapely.Polygon(poly.interiors[0]).centroid.x
        miny, maxy = poly.bounds[1] - 1, poly.bounds[3] + 1
        minx, maxx = poly.bounds[0] - 1, poly.bounds[2] + 1
        for half in (shapely.box(minx, miny, x, maxy), shapely.box(x, miny, maxx, maxy)):
            part = poly.intersection(half)
            todo += [g for g in getattr(part, "geoms", [part]) if g.geom_type == "Polygon" and not g.is_empty]
    return out


def prepare_polygons(features: list, projector: Projector, edits: dict | None = None) -> tuple[dict, Counter]:
    """Returns ({(lat, lon): [(facade, height, [(lon, lat)])]}, stats). Blocks of buildings edited to delete or to a
    model are left out."""
    by_tile, stats = defaultdict(list), Counter()
    edits = edits or {}
    for feature in features:
        p = feature["properties"]
        kind = overrides.edit_kind(edits.get(p["building_id"]))
        if kind == "delete":
            stats["blocks_deleted"] += 1
            continue
        if kind == "model":
            stats["blocks_replaced_by_model"] += 1
            continue
        polygon_m = projector.to_metric(shape(feature["geometry"]))
        pieces = [polygon_m]
        if any(len(g.interiors) for g in getattr(polygon_m, "geoms", [polygon_m])):
            pieces = split_holes(polygon_m)
            stats["courtyard_blocks_split"] += 1
        for piece in pieces:
            _add_piece(piece, p, projector, by_tile, stats)
    return by_tile, stats


def _add_piece(polygon_m, p: dict, projector: Projector, by_tile: dict, stats: Counter) -> None:
    ring, reason, had_holes = prepare_ring(polygon_m)
    stats["holes_dropped"] += had_holes
    if ring is None:
        stats[f"skipped_{reason}"] += 1
        return
    lonlat = list(zip(*projector.to_wgs84_xy([x for x, _ in ring], [y for _, y in ring])))
    centroid = Polygon(lonlat).centroid
    lat0, lon0 = math.floor(centroid.y), math.floor(centroid.x)
    if not all(lon0 <= lon <= lon0 + 1 and lat0 <= lat <= lat0 + 1 for lon, lat in lonlat):
        stats["skipped_crosses_tile"] += 1
        return
    by_tile[(lat0, lon0)].append((p["facade"], p["height_m"], lonlat))


def build_text(tile: tuple, polygons: list, zones: list, settings: dict, objects: list = (),
               extra_polygons: list = ()) -> tuple[str, dict]:
    """DSF text for one tile. zones are the area Features; only their part inside this tile becomes exclusions.
    objects: [(object path relative to the pack root, lon, lat, heading)]; extra_polygons: [(path, param, rings)]
    for placed items and trees (placements.dsf_entries)."""
    lat, lon = tile
    tile_box = box(lon, lat, lon + 1, lat + 1)
    lines = [
        "A",
        f"800 {AGENT}",
        "DSF2TEXT",
        "",
        f"PROPERTY sim/west {lon}",
        f"PROPERTY sim/east {lon + 1}",
        f"PROPERTY sim/north {lat + 1}",
        f"PROPERTY sim/south {lat}",
        "PROPERTY sim/planet earth",
        f"PROPERTY sim/creation_agent {AGENT}",
        "PROPERTY sim/overlay 1",
        "PROPERTY sim/require_facade 1/0",
    ]
    if objects:
        lines.append("PROPERTY sim/require_object 1/0")
    rect_count = 0
    for zone in zones:
        part = shape(zone["geometry"]).intersection(tile_box)
        if part.is_empty or part.area == 0:
            continue
        for rect in exclusion_rects(mapping(part), settings["dsf"]["exclusion_cell_m"]):
            value = "/".join(f"{v:.6f}" for v in rect)
            lines += [f"PROPERTY sim/exclude_{kind} {value}" for kind in settings["dsf"]["exclusion_types"]]
            rect_count += 1
    lines.append("")

    object_index: dict[str, int] = {}
    for path, *_ in objects:
        object_index.setdefault(path, len(object_index))
    facade_index: dict[str, int] = {}
    for facade, _, _ in polygons:
        facade_index.setdefault(facade, len(facade_index))
    for path, _, _ in extra_polygons:
        facade_index.setdefault(path, len(facade_index))
    lines += [f"OBJECT_DEF {path}" for path in object_index]
    lines += [f"POLYGON_DEF {path}" for path in facade_index]
    lines.append("")
    for path, lon_, lat_, heading in objects:
        lines.append(f"OBJECT {object_index[path]} {lon_:.9f} {lat_:.9f} {heading:g}")
    for facade, height, lonlat in polygons:
        lines.append(f"BEGIN_POLYGON {facade_index[facade]} {max(1, round(height))} 2")
        lines.append("BEGIN_WINDING")
        lines += [f"POLYGON_POINT {x:.9f} {y:.9f}" for x, y in lonlat]
        lines.append("END_WINDING")
        lines.append("END_POLYGON")
    for path, param, rings in extra_polygons:
        lines.append(f"BEGIN_POLYGON {facade_index[path]} {int(param)} 2")
        for ring in rings:
            lines.append("BEGIN_WINDING")
            lines += [f"POLYGON_POINT {x:.9f} {y:.9f}" for x, y in ring]
            lines.append("END_WINDING")
        lines.append("END_POLYGON")
    report = {"polygons": len(polygons), "facade_defs": len(facade_index), "exclusion_rects": rect_count,
              "objects": len(objects), "placed_polygons": len(extra_polygons)}
    return "\n".join(lines) + "\n", report


def summarize_text(text: str) -> dict:
    """Count polygons, facade definitions and exclusions in DSF text, to compare before and after compiling."""
    lines = text.splitlines()
    return {
        "polygons": sum(line.startswith("BEGIN_POLYGON") for line in lines),
        "polygon_defs": sum(line.startswith("POLYGON_DEF") for line in lines),
        "objects": sum(line.startswith(("OBJECT ", "OBJECT_MSL ", "OBJECT_AGL ")) for line in lines),
        "exclusions": sorted(
            line.split()[1].removeprefix("sim/exclude_") for line in lines if line.startswith("PROPERTY sim/exclude_")
        ),
    }


def run_dsftool(dsftool: Path, *args: str) -> subprocess.CompletedProcess:
    result = subprocess.run([str(dsftool), *args], capture_output=True, text=True, encoding="utf-8", errors="replace")
    if result.returncode != 0:
        raise RuntimeError(f"DSFTool {args[0]} failed (exit code {result.returncode}):\n{result.stdout}\n{result.stderr}")
    return result


def verify_dsf(dsftool: Path, dsf_path: Path, expected: dict, roundtrip_path: Path) -> None:
    """Decompile the DSF and check it matches the source text. DSFTool silently skips lines it cannot parse, so this check is required."""
    run_dsftool(dsftool, "--dsf2text", str(dsf_path), str(roundtrip_path))
    actual = summarize_text(roundtrip_path.read_text(encoding="utf-8", errors="replace"))
    if actual != expected:
        raise RuntimeError(f"Decompiled DSF does not match the input: input {expected}, decompiled {actual}")


def local_resolver(job):
    """Maps an asset path to the path written in the DSF: files in the job's models folder are copied to
    objects/models/ in the pack; anything else is a library path. Raises for a local-looking path that is missing."""
    def resolve(path: str) -> str:
        if overrides.model_is_local(job, path):
            return f"objects/models/{path}"
        if path.startswith(("objects/", "models/")):
            raise RuntimeError(f"{path} not found in {job.models_dir}")
        return path
    return resolve


def place_models(features: list, edits: dict, job) -> dict:
    """{tile: [(object path relative to the pack root, lon, lat, heading)]} for buildings edited to a custom model."""
    wanted = {bid: e["model"] for bid, e in edits.items() if overrides.edit_kind(e) == "model"}
    origins = overrides.building_origins([f for f in features if f["properties"]["building_id"] in wanted])
    resolve = local_resolver(job)
    out = defaultdict(list)
    for building_id, origin in origins.items():
        model = wanted[building_id]
        lon, lat = overrides.offset_lonlat(*origin, model["offset_e_m"], model["offset_n_m"])
        try:
            path = resolve(model["path"])
        except RuntimeError as exc:
            raise RuntimeError(f"Model for {building_id}: {exc}") from exc
        out[(math.floor(lat), math.floor(lon))].append((path, lon, lat, model["heading"]))
    return out


def library_report(vpaths) -> dict | None:
    """Required libraries for the virtual paths used (None when the X-Plane folder is unknown)."""
    from cityscene import library
    from cityscene.config import load_settings
    try:
        index = library.get_index(load_settings())
    except Exception as exc:  # no X-Plane folder (e.g. on a build machine): skip the check
        log.info("Library check skipped: %s", exc)
        return None
    return index.dependencies(p for p in vpaths if not p.startswith("objects/"))


def dependency_text(deps: dict | None) -> str:
    if not deps:
        return ""
    lines = ["", "Required libraries (install them in Custom Scenery):"]
    for name, paths in sorted(deps["libraries"].items()):
        lines.append(f"- {name} ({len(paths)} assets)")
    if deps["missing"]:
        lines.append("Assets not found in any installed library:")
        lines += [f"- {p}" for p in deps["missing"][:50]]
    return "\n".join(lines) + "\n"


def run(job, settings: dict) -> dict:
    dsftool = ensure_dsftool(settings)
    processed = job.processed_dir
    path = processed / "buildings_classified.geojson"
    if not path.exists():
        raise RuntimeError("No classified buildings; run classify first")
    with open(path, encoding="utf-8") as f:
        features = json.load(f)["features"]

    zones = job.zones()
    projector = Projector(metric_crs_for(zones))
    edits = overrides.load(job)
    resolve = local_resolver(job)
    for feature in features:  # per-building facades from the models folder live in the pack
        feature["properties"]["facade"] = resolve(feature["properties"]["facade"])
    by_tile, stats = prepare_polygons(features, projector, edits)
    models = place_models(features, edits, job)
    placed = placements.load(job)
    placed_objects, placed_polygons = placements.dsf_entries(placed, resolve)
    trees, tree_report = vegetation.build(job, settings)
    extra_objects, extra_polygons = placements.split_by_tile(placed_objects, placed_polygons + trees, stats)
    # Exclusions cover the whole area, so tiles without buildings are written too (to clear default autogen)
    tiles = sorted(set(tiles_for(zones_union(zones))) | set(by_tile) | set(models) | set(extra_objects)
                   | set(extra_polygons))

    build_dir = job.build_dir(settings)
    earth = build_dir / "Earth nav data"
    impostor_dir = build_dir / "objects" / "impostors"
    models_dir = build_dir / "objects" / "models"
    for old_output in (earth, impostor_dir, models_dir):
        if old_output.exists():
            shutil.rmtree(old_output)
    build_dir.mkdir(parents=True, exist_ok=True)
    used = [p for placed_list in models.values() for p, *_ in placed_list]
    used += [o[0] for o in placed_objects] + [p[0] for p in placed_polygons]
    used += [f["properties"]["facade"] for f in features]
    if any(p.startswith("objects/models/") for p in used):
        shutil.copytree(job.models_dir, models_dir)
    impostors.write_atlas(impostor_dir)
    deps = library_report(used + [t[0] for t in trees])
    (build_dir / "README.txt").write_text(ATTRIBUTION.format(name=job.scenery_name) + dependency_text(deps),
                                          encoding="utf-8")

    report = {"input_blocks": len(features), "tiles": {}, **dict(stats)}
    for tile in tiles:
        name = tile_name(*tile)
        objects, imp_stats = impostors.build_impostors(name, by_tile.get(tile, []), settings, impostor_dir, projector)
        text, tile_report = build_text(tile, by_tile.get(tile, []), zones, settings,
                                       models.get(tile, []) + extra_objects.get(tile, []) + objects,
                                       extra_polygons.get(tile, []))
        tile_report.update(imp_stats, models=len(models.get(tile, [])))
        text_path = processed / f"{name}.dsf.txt"
        text_path.write_text(text, encoding="utf-8", newline="\n")
        dsf_path = earth / tile_dir(*tile) / f"{name}.dsf"
        dsf_path.parent.mkdir(parents=True, exist_ok=True)
        run_dsftool(dsftool, "--text2dsf", str(text_path), str(dsf_path))
        verify_dsf(dsftool, dsf_path, summarize_text(text), processed / f"{name}.roundtrip.txt")
        tile_report["dsf_bytes"] = dsf_path.stat().st_size
        report["tiles"][name] = tile_report
        log.info("Tile %s: %d facade polygons (%d definitions), %d placed / tree polygons, %d exclusion rectangles, "
                 "%d bytes, decompile check passed", name, tile_report["polygons"], tile_report["facade_defs"],
                 tile_report["placed_polygons"], tile_report["exclusion_rects"], tile_report["dsf_bytes"])
    report["polygons"] = sum(t["polygons"] for t in report["tiles"].values())
    report["render_distance_km"] = settings["dsf"]["render_distance_km"]
    for key in ("impostor_objects", "impostor_triangles", "models", "placed_polygons"):
        report[key] = sum(t[key] for t in report["tiles"].values())
    report["placed_items"] = len(placed)
    report["vegetation"] = tree_report
    report["dependencies"] = deps
    if not report["impostor_objects"]:
        shutil.rmtree(impostor_dir)
    if impostor_dir.parent.is_dir() and not any(impostor_dir.parent.iterdir()):
        impostor_dir.parent.rmdir()
    report["roundtrip_verified"] = True
    with open(processed / "build_report.json", "w", encoding="utf-8") as f:
        json.dump(report, f, ensure_ascii=False, indent=2)
    transfer.write_job_data(job, build_dir)
    skipped = {k: v for k, v in report.items() if k.startswith("skipped_")}
    log.info("%d blocks -> %d facade polygons; skipped %s; holes dropped %d", len(features), report["polygons"],
             skipped or 0, report.get("holes_dropped", 0))
    if report["models"] or report.get("blocks_deleted"):
        log.info("Edits: %d custom models placed, %d blocks replaced by models, %d blocks deleted", report["models"],
                 report.get("blocks_replaced_by_model", 0), report.get("blocks_deleted", 0))
    if placed:
        log.info("Placed items: %d (%d skipped across tile edges)", len(placed),
                 report.get("placements_skipped_cross_tile", 0))
    if deps:
        log.info("Libraries used: %s", ", ".join(sorted(deps["libraries"])) or "none")
        if deps["missing"]:
            log.warning("%d asset paths are not exported by any installed library (they will not show): %s",
                        len(deps["missing"]), ", ".join(deps["missing"][:5]))
    log.info("Render distance %g km: %d distant-block objects, %d triangles", report["render_distance_km"],
             report["impostor_objects"], report["impostor_triangles"])
    log.info("Scenery pack: %s", build_dir)
    return report
