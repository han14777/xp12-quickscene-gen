"""Scenery packs as portable jobs: every generated pack carries its job in <pack>/quickscene/, so a pack made by
this tool (in another copy, from someone else, or installed in Custom Scenery) can be imported back as a job,
edited, refreshed from OSM and regenerated.

<pack>/quickscene/:
  job.json                  {"format", "name", "scenery_name", "options", "generated_at"}
  zone.geojson              the area
  overrides.json            per-building edits (when any)
  placements.json           placed objects, facades, forests, polygons and lines (when any)
  buildings_clean.geojson   output of clean, so an imported job can be edited and regenerated without downloading
Custom models are already in <pack>/objects/models/ (a copy of the job's models folder) and are copied back.

Three kinds of import, best first:
- "job": the pack (or the Custom Scenery link to it) sits in <copy>/build/ of another copy of this tool whose
  <copy>/jobs/ still has the job that made it: the whole job folder is copied (OSM cache included)
- "data": the pack carries quickscene/ (cityscene/ in packs made before the tool was renamed)
- "legacy": a pack from a version without quickscene/ (recognised by the README.txt this tool writes): the area is
  rebuilt from the DSF exclusion rectangles and the render distance from the distant-block OBJs; OSM data has to
  be downloaded again before editing
"""

import json
import shutil
import tempfile
from datetime import datetime
from pathlib import Path

from shapely.geometry import box, mapping
from shapely.ops import unary_union

from quickscene import classify
from quickscene.config import Job, check_name, list_jobs, xplane_root, project_path
from quickscene.log import get_logger

log = get_logger("import")

# Packs made before the tool was renamed (xp12-cityscene-gen -> QuickScene) use the old names; both are read
DATA_DIR = "quickscene"
OLD_DATA_DIRS = ("cityscene",)
FORMAT = 1
README_MARKS = ("Generated by QuickScene", "Generated by xp12-cityscene-gen")
AGENTS = ("QuickScene", "xp12-cityscene-gen")


def data_dir(pack: Path) -> Path:
    """The folder holding the job inside a pack (new name first, then the old one)."""
    for name in (DATA_DIR, *OLD_DATA_DIRS):
        if (pack / name / "job.json").is_file():
            return pack / name
    return pack / DATA_DIR


def write_job_data(job, build_dir: Path) -> None:
    """Called by build_dsf after a successful build."""
    out = build_dir / DATA_DIR
    for old in [out] + [build_dir / name for name in OLD_DATA_DIRS]:
        if old.exists():
            shutil.rmtree(old)
    out.mkdir(parents=True)
    meta = job.meta
    (out / "job.json").write_text(json.dumps({
        "format": FORMAT, "name": job.name, "scenery_name": job.scenery_name, "options": meta.get("options", {}),
        "source": job.source,
        "generated_at": datetime.now().isoformat(timespec="seconds")}, ensure_ascii=False, indent=2), encoding="utf-8")
    shutil.copyfile(job.zone_path, out / "zone.geojson")
    if job.overrides_path.exists():
        shutil.copyfile(job.overrides_path, out / "overrides.json")
    if (job.root / "placements.json").exists():
        shutil.copyfile(job.root / "placements.json", out / "placements.json")
    clean = job.processed_dir / "buildings_clean.geojson"
    if clean.exists():
        shutil.copyfile(clean, out / "buildings_clean.geojson")


def source_job(pack: Path) -> Path | None:
    """The job folder that made this pack, when the pack is the build output of another copy of this tool."""
    try:
        real = pack.resolve()
    except OSError:
        return None
    jobs = real.parent.parent / "jobs"
    if real.parent.name != "build" or not jobs.is_dir():
        return None
    for meta in jobs.glob("*/job.json"):
        try:
            if json.loads(meta.read_text(encoding="utf-8")).get("scenery_name") == real.name:
                return meta.parent
        except (OSError, ValueError):
            continue
    return None


def pack_kind(pack: Path) -> str | None:
    """"job", "data", "legacy" (see the module notes), or None (not made by this tool)."""
    if not (data_dir(pack) / "job.json").is_file() and pack_kind_basic(pack) is None:
        return None
    return "job" if source_job(pack) else pack_kind_basic(pack)


def pack_kind_basic(pack: Path) -> str | None:
    if (data_dir(pack) / "job.json").is_file():
        return "data"
    readme = pack / "README.txt"
    if readme.is_file() and any(mark in readme.read_text(encoding="utf-8", errors="replace") for mark in README_MARKS):
        return "legacy"
    return None


def _same(a: Path, b: Path) -> bool:
    try:
        return a.resolve() == b.resolve()
    except OSError:
        return False


def find_packs(settings: dict) -> list:
    """Packs made by this tool in Custom Scenery and in the build folder, except those that are already the build
    output of a job in this copy."""
    own, jobs_by_pack = [], {}
    for name in list_jobs(settings):
        job = Job.open(name, settings)
        own.append(job.build_dir(settings))
        jobs_by_pack[job.scenery_name] = name
    roots = [("build", project_path(settings["paths"]["build_dir"]))]
    root = xplane_root(settings)
    if root:
        roots.append(("custom_scenery", root / "Custom Scenery"))
    found, seen = [], []
    for source, folder in roots:
        if not folder.is_dir():
            continue
        for pack in sorted(folder.iterdir()):
            try:
                kind = pack_kind(pack) if pack.is_dir() else None
            except OSError:
                continue
            if not kind or any(_same(pack, o) for o in own) or any(_same(pack, s) for s in seen):
                continue
            seen.append(pack)
            meta = _meta_for(pack, kind)
            name = meta.get("name") or _default_name(pack.name)
            # A job here already uses this pack name, i.e. it was imported before: importing again replaces it
            found.append({"path": str(pack), "folder": pack.name, "source": source, "kind": kind, "name": name,
                          "existing_job": jobs_by_pack.get(meta.get("scenery_name") or pack.name)})
    return found


def _read_meta(pack: Path) -> dict:
    return json.loads((data_dir(pack) / "job.json").read_text(encoding="utf-8"))


def _meta_for(pack: Path, kind: str) -> dict:
    if kind == "job":
        return json.loads((source_job(pack) / "job.json").read_text(encoding="utf-8"))
    return _read_meta(pack) if kind == "data" else {}


def _default_name(folder: str) -> str:
    name = folder.removeprefix("CityScene_")
    cleaned = "".join(c if c.isalnum() or c in "_-" else "_" for c in name)[:64]
    return cleaned or "imported"


def legacy_zone(pack: Path, settings: dict) -> dict:
    """Area of a legacy pack: the union of its exclusion rectangles (decompiled with DSFTool)."""
    from quickscene.build_dsf import run_dsftool
    from quickscene.tools_setup import ensure_dsftool

    dsftool = ensure_dsftool(settings)
    dsfs = sorted((pack / "Earth nav data").rglob("*.dsf"))
    if not dsfs:
        raise ValueError(f"No DSF found in {pack}")
    rects = []
    with tempfile.TemporaryDirectory() as tmp:
        for n, dsf in enumerate(dsfs):
            text_path = Path(tmp) / f"{n}.txt"
            run_dsftool(dsftool, "--dsf2text", str(dsf), str(text_path))
            text = text_path.read_text(encoding="utf-8", errors="replace")
            if not any(f"sim/creation_agent {agent}" in text for agent in AGENTS):
                raise ValueError(f"{dsf.name} was not generated by QuickScene")
            for line in text.splitlines():
                if line.startswith("PROPERTY sim/exclude_fac "):
                    rects.append(box(*(float(v) for v in line.split()[2].split("/"))))
    if not rects:
        raise ValueError(f"No exclusion zones in {pack}; cannot recover the area")
    area = unary_union(rects).buffer(0)
    geoms = getattr(area, "geoms", [area])
    return {"type": "FeatureCollection", "features": [
        {"type": "Feature", "properties": {}, "geometry": mapping(g.simplify(1e-6))} for g in geoms]}


def legacy_render_distance(pack: Path) -> float | None:
    """Render distance (km) of a legacy pack from its distant-block OBJs (the far end of their second ATTR_LOD)."""
    for obj in sorted((pack / "objects" / "impostors").glob("*.obj"))[:1]:
        lods = [line.split() for line in obj.read_text(encoding="ascii", errors="replace").splitlines()
                if line.startswith("ATTR_LOD")]
        if len(lods) >= 2:
            return float(lods[1][2]) / 1000
    return None


def import_pack(pack: Path, settings: dict, name: str | None = None, overwrite: bool = False) -> dict:
    """Create a job from a pack made by this tool and copy the pack into the build folder. Returns a summary."""
    pack = Path(pack)
    kind = pack_kind(pack) if pack.is_dir() else None
    if kind is None:
        raise ValueError(f"{pack} is not a scenery pack made by QuickScene")
    meta = _meta_for(pack, kind)
    if meta.get("format", FORMAT) > FORMAT:
        raise ValueError("This pack was made by a newer version of QuickScene; update the tool first")
    stored_name = meta.get("name") or _default_name(pack.name)
    name = check_name(name or stored_name)
    scenery_name = check_name(meta.get("scenery_name") or pack.name)

    def pack_owner(pack_name):
        return next((o for o in list_jobs(settings) if o != name and Job.open(o, settings).scenery_name == pack_name), None)

    owner = pack_owner(scenery_name)
    if owner and name != stored_name:
        # Imported as a copy under a new name: the pack gets a matching name too, so both can be installed
        scenery_name = check_name(f"CityScene_{name}")
        owner = pack_owner(scenery_name)
    if owner:
        raise ValueError(f"Job {owner} already uses the pack name {scenery_name}; import under another name")

    source = source_job(pack) if kind == "job" else None
    if kind == "job":
        zone = json.loads((source / "zone.geojson").read_text(encoding="utf-8"))
        options = meta.get("options", {})
    elif kind == "data":
        zone = json.loads((data_dir(pack) / "zone.geojson").read_text(encoding="utf-8"))
        options = meta.get("options", {})
    else:
        zone = legacy_zone(pack, settings)
        distance = legacy_render_distance(pack)
        options = {"dsf": {"render_distance_km": distance}} if distance else {}
    existed = (project_path(settings["paths"]["jobs_dir"]) / name / "job.json").exists()
    job = Job.create(name, zone, settings, scenery_name, options, overwrite=overwrite, source=meta.get("source"))
    if existed:
        # Replacing a job: drop what belonged to the old one
        for old in (job.processed_dir, job.raw_dir, job.models_dir):
            if old.exists():
                shutil.rmtree(old)
        job.overrides_path.unlink(missing_ok=True)

    data = source if source else data_dir(pack)
    if source:
        # Everything the other copy has: OSM cache, intermediate results, edits, models
        for sub in ("raw", "processed", "models"):
            if (source / sub).is_dir():
                shutil.copytree(source / sub, job.root / sub)
    elif (pack / "objects" / "models").is_dir():
        shutil.copytree(pack / "objects" / "models", job.models_dir)
    if (data / "overrides.json").is_file():
        shutil.copyfile(data / "overrides.json", job.overrides_path)
    (job.root / "placements.json").unlink(missing_ok=True)
    if (data / "placements.json").is_file():
        shutil.copyfile(data / "placements.json", job.root / "placements.json")
    buildings = 0
    clean = data / ("processed" if source else ".") / "buildings_clean.geojson"
    if clean.is_file():
        job.processed_dir.mkdir(parents=True, exist_ok=True)
        if not source:
            shutil.copyfile(clean, job.processed_dir / "buildings_clean.geojson")
        # Re-run classify with this copy's code and settings so the preview and edit flags are current
        buildings = classify.run(job, job.settings(settings))["blocks"]

    target = job.build_dir(settings)
    if not _same(pack, target):
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(pack, target)
    summary = {"name": job.name, "scenery_name": scenery_name, "kind": kind, "blocks": buildings,
               "edits": len(json.loads(job.overrides_path.read_text(encoding="utf-8"))["buildings"])
               if job.overrides_path.exists() else 0,
               "models": sum(1 for _ in job.models_dir.rglob("*.obj")) if job.models_dir.is_dir() else 0,
               "options": options}
    log.info("Imported %s as job %s (%s): %d blocks, %d edits, %d models", pack, job.name, kind, buildings,
             summary["edits"], summary["models"])
    return summary
