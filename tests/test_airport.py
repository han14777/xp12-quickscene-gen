def test_aptdat_round_trip_keeps_everything():
    data = aptdat.parse_text(APT)[0]
    assert data["header"] == {"type": "land", "icao": "YTST", "name": "Test Field", "elevation_ft": 433.0}
    assert data["meta"]["city"] == "Testville"
    rwy = data["runways"][0]
    assert [e["name"] for e in rwy["ends"]] == ["09", "27"] and rwy["ends"][1]["displaced_m"] == 150
    assert rwy["ends"][0]["approach_lights"] == 8 and rwy["ends"][1]["reil"] == 2
    pav = data["pavements"][0]
    assert len(pav["rings"]) == 2 and pav["rings"][0][1]["ctrl"] == [144.812, -37.697]
    assert pav["rings"][0][1]["line"] == 1 and pav["rings"][0][1]["light"] == 102
    line = data["lines"][0]
    assert not line["closed"] and line["nodes"][1]["ctrl"] and line["nodes"][1]["light"] == 101
    assert data["startups"][0]["airlines"] == ["qfa", "vaa"] and data["startups"][0]["width_code"] == "E"
    assert [f["mhz"] for f in data["frequencies"]] == [128.3, 118.5]  # 54 row in 10 kHz units
    assert data["taxi_edges"][1]["active"] == [{"type": "departure", "runways": "09"}]
    assert data["light_fixtures"][0]["runway"] == "09"
    assert [r.split()[0] for r in data["raw"]] == ["1000", "1001", "1206", "1400"]

    text = aptdat.write_file([data])
    again = aptdat.parse_text(text)[0]
    for key in model.LISTS:
        assert len(again[key]) == len(data[key]), key
    strip = lambda d: json.loads(json.dumps({k: v for k, v in d.items() if k not in model.LISTS}))
    assert strip(again) == strip(data)
    assert again["pavements"][0]["rings"] == data["pavements"][0]["rings"]
    assert again["lines"][0]["nodes"] == data["lines"][0]["nodes"]
    assert text.rstrip().endswith("99") and "\n54 " not in text and "1054 118500 Tower" in text
    # ATC flows go before the route network, truck rows after it (as WED writes them)
    order = [line.split()[0] for line in text.splitlines()[3:] if line.strip()]
    assert order.index("1001") < order.index("1200") < order.index("1206")


def test_validation_flags_real_problems():
    data = aptdat.parse_text(APT)[0]
    assert validate.summary(validate.check(data))["errors"] == 0
    bad = json.loads(json.dumps(data))
    bad["runways"][0]["ends"][1]["name"] = "26"
    bad["startups"][1]["type"] = "tie-down"
    bad["taxi_edges"].append({"id": "x", "a": 0, "b": 99, "oneway": False, "kind": "taxiway", "name": "",
                              "active": []})
    bad["signs"][0]["text"] = "{@Y}A{"
    bad["frequencies"][0]["mhz"] = 150
    codes = {f["code"] for f in validate.check(bad) if f["level"] == "error"}
    assert {"runway_pair", "startup_type", "taxi_edge_node", "sign_text", "frequency_range"} <= codes
    swapped = json.loads(json.dumps(data))
    a, b = swapped["runways"][0]["ends"]
    a["lon"], b["lon"] = b["lon"], a["lon"]
    assert "runway_heading" in {f["code"] for f in validate.check(swapped)}
    assert "no_runway" in {f["code"] for f in validate.check(model.empty("ABCD", "x", 10))}


def test_global_index_finds_airports(tmp_path):
    path = tmp_path / "apt.dat"
    path.write_bytes(APT.replace("99\n", "") .encode() + b"\n17 10 0 0 XH1 Heli\n102 H1 1 2 0 10 10 1 0 0 0 0\n99\n")
    index = build_index(path)
    assert set(index) == {"YTST", "XH1"}
    start, length, name, lon, lat, elev = index["YTST"]
    assert name == "Test Field" and elev == 433 and round(lat, 1) == -37.7
    assert path.read_bytes()[start:start + length].decode().startswith("1   433")


def _osm():
    nodes, ways = [], []

    def n(i, lon, lat, tags=None):
        e = {"type": "node", "id": i, "lon": lon, "lat": lat}
        if tags:
            e["tags"] = tags
        nodes.append(e)

    n(1, 144.80, -37.70)
    n(2, 144.83, -37.70)
    n(3, 144.81, -37.70)
    n(4, 144.81, -37.698)
    n(5, 144.815, -37.698)
    n(6, 144.815, -37.6975, {"aeroway": "parking_position", "ref": "5"})
    n(7, 144.82, -37.699, {"aeroway": "windsock"})
    for i, (lon, lat) in enumerate([(144.79, -37.69), (144.84, -37.69), (144.84, -37.71), (144.79, -37.71)], 10):
        n(i, lon, lat)
    ways.append({"type": "way", "id": 100, "nodes": [1, 3, 2],
                 "tags": {"aeroway": "runway", "ref": "27/09", "width": "45", "surface": "asphalt"}})
    ways.append({"type": "way", "id": 101, "nodes": [3, 4, 5], "tags": {"aeroway": "taxiway", "ref": "A"}})
    ways.append({"type": "way", "id": 102, "nodes": [10, 11, 12, 13, 10],
                 "tags": {"aeroway": "aerodrome", "icao": "YTST", "name": "Test", "ele": "132"}})
    return {"elements": nodes + ways}


def test_osm_draft():
    data, report = osm_airport.convert(_osm(), make_settings_stub(), "YTST")
    rwy = data["runways"][0]
    # ref 27/09 but the way runs west -> east, so its first end is 09
    assert [e["name"] for e in rwy["ends"]] == ["09", "27"] and rwy["width_m"] == 45
    assert data["header"]["elevation_ft"] == 433 and data["boundaries"]
    assert report["taxi_edges"] == 4 and {e["kind"] for e in data["taxi_edges"]} == {"runway", "taxiway_E"}
    stand = data["startups"][0]
    assert stand["name"] == "Stand 5" and abs(stand["heading"]) < 1  # faces north, away from the taxiway
    assert data["windsocks"] and data["pavements"]
    assert validate.summary(validate.check(data))["errors"] == 0


def make_settings_stub():
    from cityscene.config import load_settings
