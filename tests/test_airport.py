def test_blank_and_export(tmp_path):
    tool = _dsftool()
    if not tool:
        pytest.skip("DSFTool not available")
    settings = make_settings(tmp_path)
    settings["paths"]["airports_dir"] = str(tmp_path / "airports")
    settings["tools"]["dsftool"] = tool
    data = aptdat.parse_text(APT)[0]
    data["placements"] = [{"path": "lib/airport/Ramp_Equipment/Tug.obj", "lon": 144.806, "lat": -37.697,
                           "heading": 10, "agl": 4},
                          {"path": "lib/airport/buildings/warehouses/flat/white.fac",
                           "rings": [[[144.807, -37.6965], [144.808, -37.6965], [144.808, -37.696]]], "height": 9}]
    data["options"]["exclude"] = ["obj", "fac", "net"]
    p = project.AirportProject.create("YTST", data, settings)
    saved = p.load()
    assert saved["options"]["exclude"] == ["obj", "fac"]  # roads are never excluded
    assert p.scenery_name == "YTST_Test_Field"
    report = project.export(p, settings)
    dsf = report["dsf"]["-38+144"]
    assert dsf["objects"] == 1 and dsf["placed_polygons"] == 1 and dsf["exclusion_rects"] > 0
    apt = (p.build_dir(settings) / "Earth nav data" / "apt.dat").read_text(encoding="utf-8")
    assert apt.startswith("I\n1200") and "1   433" not in apt and "1 433 0 0 YTST Test Field" in apt
    roundtrip = (p.root / "processed" / "-38+144.roundtrip.txt").read_text(encoding="utf-8", errors="replace")
    assert "OBJECT_AGL" in roundtrip
    # history keeps earlier saves
    p.save(saved)
    assert len(list((p.root / "history").glob("*.json"))) == 1
    # an airport with errors is not exported
    broken = p.load()
    broken["runways"][0]["ends"][1]["name"] = "26"
    p.save(broken)
    with pytest.raises(RuntimeError):
        project.export(p, settings)
    assert create.blank("YNEW", "New", 144.9, -37.8)["runways"][0]["ends"][1]["name"] == "27"
